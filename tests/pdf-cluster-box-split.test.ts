describe("cluster table around a text box", () => {
  it("does not read body lines above and below a boxed block as one table", () => {
    const items = ITEMS.map(([text, x, y, w, h, fontSize]) => ({ text, x, y, w, h, fontSize, fontName: "F", isHidden: false }) as NormItem)
    const fnArray: number[] = [OPS.setLineWidth]
    const argsArray: unknown[][] = [[0.5]]
    for (const sg of [[67.5, 714.239, 527.75, 714.239], [67.5, 456.889, 527.75, 456.889], [67.75, 456.639, 67.75, 714.489], [527.5, 456.639, 527.5, 714.489]]) {
      fnArray.push(OPS.constructPath, OPS.stroke)
      argsArray.push([[OPS.moveTo, OPS.lineTo], sg], [])
    }
    const blocks = extractPageBlocksWithLines(items, 1, { fnArray, argsArray }, 595, 842)
    assert.equal(blocks.filter(b => b.type === "table").length, 0)
    const text = blocks.map(b => b.text ?? "").join("\n")
    assert.ok(text.indexOf("著作权人") < text.indexOf("上述著作物"), text)
  })
})
